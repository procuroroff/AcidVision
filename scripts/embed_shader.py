#!/usr/bin/env python3
"""Embed Shaders.metal into a C/Objective-C header.

Theos with the Linux iOS cross-toolchain does not ship Apple's `metal`
compiler, so the shader is compiled at runtime by MTLLibrary
`newLibraryWithSource:options:error:`. This script turns the readable
Shaders.metal into an NSString literal.

Usage:
    python3 scripts/embed_shader.py Shaders.metal ShadersSource.h

The generated header is committed; CI regenerates it and fails if the
working tree changes, so the two files cannot silently diverge.
"""

from __future__ import annotations

import pathlib
import sys


def c_literal(source: str) -> str:
    out = []
    for line in source.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\r", "")
            .replace("\n", "\\n")
        )
        out.append(f'    @"{escaped}"')
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    src = pathlib.Path(sys.argv[1])
    dst = pathlib.Path(sys.argv[2])
    text = src.read_text(encoding="utf-8")

    header = (
        "// AUTO-GENERATED by scripts/embed_shader.py from Shaders.metal.\n"
        "// Do not edit by hand: change Shaders.metal and rerun the script.\n"
        "#pragma once\n"
        "#import <Foundation/Foundation.h>\n\n"
        "static NSString *const kAcidShaderSource =\n"
        f"{c_literal(text)};\n"
    )
    dst.write_text(header, encoding="utf-8", newline="\n")
    print(f"embedded {src} -> {dst} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
